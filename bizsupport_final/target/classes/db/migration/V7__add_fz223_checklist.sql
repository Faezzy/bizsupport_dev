    (9, 'Заключить договор',
        'При победе — подписать договор УКЭП в сроки, установленные Положением о закупке заказчика.',
        'Сроки и порядок заключения договора регулируются Положением, а не 44-ФЗ.')
) AS v(step_order, title, description, hint)
WHERE c.title = 'Чек-лист: участие в закупке по 223-ФЗ'
  AND c.is_template = TRUE;
