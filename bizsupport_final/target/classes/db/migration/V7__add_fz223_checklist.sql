-- Процесс участия в закупках госкомпаний отличается от 44-ФЗ:
-- Положение о закупке, коммерческие ЭТП, неценовые критерии.
-- ID не хардкодятся — checklist_id берётся подзапросом по title.
-- ============================================================

-- Шаблон чек-листа, привязанный к сценарию 223-ФЗ
INSERT INTO checklists (scenario_id, title, description, is_template)
SELECT id,
       'Чек-лист: участие в закупке по 223-ФЗ',
       'Пошаговая инструкция участия в закупках госкомпаний по 223-ФЗ — от изучения Положения о закупке до заключения договора',
       TRUE
FROM procurement_scenarios
WHERE law_type = 'FZ_223'
ORDER BY id
LIMIT 1;

-- Шаги чек-листа (checklist_id определяется по заголовку шаблона)
INSERT INTO checklist_steps (checklist_id, step_order, title, description, hint)
SELECT c.id, v.step_order, v.title, v.description, v.hint
FROM checklists c
CROSS JOIN (VALUES
    (1, 'Изучить Положение о закупке заказчика',
        'Каждая госкомпания утверждает собственное Положение о закупке. Изучите его до подачи заявки.',
        'Положение публикуется на zakupki.gov.ru в карточке заказчика, раздел 223-ФЗ.'),
    (2, 'Получить усиленную квалифицированную ЭЦП (УКЭП)',
        'Оформить УКЭП в аккредитованном удостоверяющем центре для подписания заявок и договоров.',
        'Та же подпись подходит и для 44-ФЗ, и для коммерческих ЭТП.'),
    (3, 'Зарегистрироваться в ЕИС',
        'Пройти регистрацию в Единой информационной системе — извещения по 223-ФЗ публикуются там же.',
        'Регистрация в ЕИС бесплатна и нужна для участия в большинстве закупок.'),
    (4, 'Зарегистрироваться на коммерческих ЭТП',
        'Закупки по 223-ФЗ проводятся на коммерческих площадках, отличных от площадок 44-ФЗ.',
        'Основные ЭТП: B2B-Center, ТЭК-Торг, Газпромбанк, Фабрикант, РТС-тендер (секция 223-ФЗ).'),
    (5, 'Проверить статус МСП в реестре',
        'Для участия в закупках по квоте для МСП компания должна быть в реестре МСП.',
        'Проверка: rmsp.nalog.ru. Реестр обновляется 10 числа каждого месяца.'),
    (6, 'Найти закупку и изучить документацию',
        'Подобрать закупку по ОКПД2 и ключевым словам, изучить ТЗ, проект договора и критерии оценки.',
        'Обратите внимание на вес ценовых и неценовых критериев — по 223-ФЗ они могут быть субъективными.'),
    (7, 'Подготовить заявку с учётом неценовых критериев',
        'Собрать портфолио, рекомендательные письма, подтверждения опыта — это влияет на оценку.',
        'По 223-ФЗ деловая репутация и опыт часто весомее цены.'),
    (8, 'Обеспечить заявку и подать её в срок',
        'Учесть требования к обеспечению (до 30% цены договора) и короткие сроки подачи (иногда 5 раб. дней).',
